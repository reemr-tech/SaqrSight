"""Write eval/results/text_report.md: the text-indicator evaluation as tables for the project report.

Reads (run the evaluations first):
  eval/results/text_lexicon_v1.0.json   lexicon 1.0 (recorded before the 1.1 changes)
  eval/results/text.json                current lexicon (eval_text.py)
  eval/results/text_ml.json             TF-IDF + logistic regression comparison (eval_text_ml.py)

Usage: python -I eval/make_text_report.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "eval" / "results"
CATS = [("urgency", "Urgency"), ("fear", "Fear / alarm"), ("manipulation", "Manipulation"),
        ("share_pressure", "Share pressure")]
PHENOMENA = [("negation", "Negation (“do not share”)"), ("quote", "Quotation / reported"),
             ("debunk", "Debunking a rumour"), ("warning", "Official warning"), ("neutral", "Neutral news")]


def f(x):
    return "–" if x is None else f"{x:.2f}"


def count(path, lang=None):
    rows = [json.loads(x) for x in open(path, encoding="utf-8")]
    return len([r for r in rows if lang is None or r["lang"] == lang])


def main():
    v10 = json.load(open(RES / "text_lexicon_v1.0.json"))
    v11 = json.load(open(RES / "text.json"))
    ml = json.load(open(RES / "text_ml.json"))
    data = ROOT / "eval" / "data"
    L = []
    L.append("# Text indicators – evaluation results\n")
    L.append("Generated by `eval/make_text_report.py`. All numbers are measured; see `eval/data/README.md` "
             "for how the data was written and labelled.\n")
    L.append("## Data\n")
    L.append("| Set | Purpose | English | Arabic |\n|---|---|---|---|")
    for name, purpose in [("dev", "development (lexicon 1.0 written from it)"),
                          ("dev_dialect", "development (lexicon 1.1 dialect additions)"),
                          ("test", "test v1 (no longer blind: its errors were seen before 1.1)"),
                          ("test_v2", "**test v2 – blind**, frozen before 1.1 (git commit 7ed7538)"),
                          ("real_dev", "real posts – development half"),
                          ("real_test", "**real posts – test half** (never used for changes)")]:
        p = data / f"text_indicators_{name}.jsonl"
        if p.exists():
            L.append(f"| `{name}` | {purpose} | {count(p, 'en')} | {count(p, 'ar')} |")
    L.append("\nAll posts are synthetic (written by the developer, no personal data) and labelled by one "
             "annotator. Each category has few positive examples per language, so differences of a few "
             "points are not meaningful. A reviewed set of real posts is the next step (`eval/annotation/`).\n")

    if "real_test" in v11 and "real_test" in ml:
        L.append("## 0. Real posts (reviewed, held-out half)\n")
        L.append("| Method | Language | n | Precision | Recall | F1 |\n|---|---|---|---|---|---|")
        for label, res in [("Lexicon (current)", v11), ("TF-IDF + logistic regression", ml)]:
            for lang, name in (("en", "English"), ("ar", "Arabic")):
                d = res["real_test"][lang]
                if d["n"]:
                    m = d["metrics"]["micro"]
                    L.append(f"| {label} | {name} | {d['n']} | {f(m['precision'])} | {f(m['recall'])} | {f(m['f1'])} |")
        L.append("")
    L.append("## 1. Overall results on the blind test (v2)\n")
    L.append("Micro-averaged over the four categories. Precision = when it flags something, how often it is right; "
             "recall = how many real indicators it finds.\n")
    L.append("| Method | Language | Precision | Recall | F1 |\n|---|---|---|---|---|")
    for label, res in [("Lexicon 1.0 (before)", v10), ("**Lexicon 1.1 (current)**", v11), ("TF-IDF + logistic regression", ml)]:
        for lang, name in (("en", "English"), ("ar", "Arabic")):
            m = res["test_v2"][lang]["metrics"]["micro"]
            L.append(f"| {label} | {name} | {f(m['precision'])} | {f(m['recall'])} | {f(m['f1'])} |")
    L.append("")

    L.append("## 2. Per category on the blind test (v2), F1\n")
    L.append("| Category | Lexicon 1.1 – EN | Lexicon 1.1 – AR | ML – EN | ML – AR |\n|---|---|---|---|---|")
    for key, name in CATS:
        vals = [v11["test_v2"]["en"]["metrics"][key]["f1"], v11["test_v2"]["ar"]["metrics"][key]["f1"],
                ml["test_v2"]["en"]["metrics"][key]["f1"], ml["test_v2"]["ar"]["metrics"][key]["f1"]]
        L.append(f"| {name} | " + " | ".join(f(v) for v in vals) + " |")
    L.append("")

    L.append("## 3. False alarms on posts that must not be flagged (blind test v2)\n")
    L.append("Share of these posts where any indicator was reported (lower is better).\n")
    L.append("| Case | n (EN/AR) | Lexicon 1.1 – EN | Lexicon 1.1 – AR | ML – EN | ML – AR |\n|---|---|---|---|---|---|")
    for key, name in PHENOMENA:
        k = f"false_alarm_rate_{key}"
        e, a = v11["test_v2"]["en"]["metrics"].get(k), v11["test_v2"]["ar"]["metrics"].get(k)
        me, ma = ml["test_v2"]["en"]["metrics"].get(k), ml["test_v2"]["ar"]["metrics"].get(k)
        if e or a:
            L.append(f"| {name} | {(e or {}).get('n', 0)}/{(a or {}).get('n', 0)} | {f((e or {}).get('rate'))} | "
                     f"{f((a or {}).get('rate'))} | {f((me or {}).get('rate'))} | {f((ma or {}).get('rate'))} |")
    L.append("")

    L.append("## 4. Earlier test set (v1) for reference\n")
    L.append("| Method | Language | Precision | Recall | F1 |\n|---|---|---|---|---|")
    for label, res in [("Lexicon 1.0", v10), ("Lexicon 1.1", v11), ("TF-IDF + logistic regression", ml)]:
        for lang, name in (("en", "English"), ("ar", "Arabic")):
            m = res["test"][lang]["metrics"]["micro"]
            L.append(f"| {label} | {name} | {f(m['precision'])} | {f(m['recall'])} | {f(m['f1'])} |")
    L.append("\nTest v1 is not blind for lexicon 1.1: its missed examples were known when 1.1 was written, so "
             "its 1.1 scores are optimistic. Use test v2 (section 1) as the result.\n")

    L.append("## 5. Remaining errors of lexicon 1.1 on the blind test (v2)\n")
    L.append("| ID | Case | Missed | Wrongly added | Post |\n|---|---|---|---|---|")
    for lang in ("en", "ar"):
        for e in v11["test_v2"][lang]["errors"]:
            text = e["text"].replace("|", "/")
            L.append(f"| {e['id']} | {e['phenomenon']} | {', '.join(e['missed']) or '–'} | "
                     f"{', '.join(e['extra']) or '–'} | {text} |")
    L.append("")

    L.append("## 6. What this shows\n")
    L.append("- Adding Gulf-dialect and everyday wording (lexicon 1.1) raised recall on unseen posts without "
             "adding false alarms: negation, quotations, debunks and official warnings were still not flagged.")
    L.append("- Fear / alarm wording remains the weakest category: it is expressed in many different ways "
             "(\"people are trapped\", \"something bad is happening\") that a word list cannot cover fully.")
    L.append("- With about 90 training posts, the machine-learning model found fewer indicators overall than the "
             "transparent rules. Machine learning needs more labelled data; the comparison should be "
             "repeated on the real, reviewed posts.")
    better = []
    for key, name in CATS:
        for lang, lname in (("en", "English"), ("ar", "Arabic")):
            r, m = v11["test_v2"][lang]["metrics"][key]["f1"], ml["test_v2"][lang]["metrics"][key]["f1"]
            if r is not None and m is not None and m > r:
                better.append(f"{name} in {lname} (F1 {m:.2f} vs {r:.2f})")
    if better:
        L.append("- The machine-learning model did better than the rules on: " + "; ".join(better) + ". "
                 "Because it learns from letter patterns rather than fixed phrases, it generalises better to "
                 "categories with very varied wording – a combined approach (rules + model) is worth testing "
                 "in Senior Project 2.")
    L.append("- The rules show the exact words behind every finding, which is what the report needs to explain "
             "itself to the public.\n")
    (RES / "text_report.md").write_text("\n".join(L), encoding="utf-8")
    print((RES / "text_report.md").read_text(encoding="utf-8")[:3500])


if __name__ == "__main__":
    main()
